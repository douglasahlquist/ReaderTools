#!/usr/bin/env python3
"""Turns workspace_islam/QuranReader/quran.tsv (surah, ayah, verse_key, arabic, english,
verse_url, source_page_url) into ChineseReader library pages: one page per surah, in the same
verse-table format as the Bible passages, so Quick Read, Comparative views, notes, links,
swipe-to-resize and ‹ › paging all work.

    | Arabic | Romanization | Pickthall |
    | 1 بِسْمِ ٱللَّهِ … | Bismi llāhi r-raḥmāni r-raḥīm | In the name of Allah, … |

No Hanzi or Pinyin columns: the header names only the versions, and the verse number leads the
first cell (the reader app takes it off and shows it beside the verse).
The romanization is generated by arabic_roman.py (approximate, not a published one).

Output goes to a PRIVATE staging folder by default: the Sahih International translation is
copyrighted (© Saheeh International), so don't copy it into the public ChineseReaderText
until its use is cleared. --no-english leaves that column out (Arabic + romanization only,
which can be public: the Uthmani text itself is not copyrighted).

    python3 quran_pages.py                       # → ~/Documents/workspace_islam/ChineseReaderText_staging/islam
    python3 quran_pages.py --out ~/Documents/workspace_chinese/ChineseReaderText/islam --no-english
Pickthall's English (1930, public domain in the US) is added from --pickthall when the file exists.

Layout: <out>/README.md (the section index, surahs in groups of 20), <out>/quran/NNN-slug.md,
and <out>/catalog-entry.md (the `## islam · …` block to paste into catalog.md).
"""
import argparse
import csv
import os
import re
import sys
from collections import OrderedDict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import arabic_roman  # noqa: E402

HOME = os.path.expanduser("~")
DEFAULT_TSV = os.path.join(HOME, "Documents/workspace_islam/QuranReader/quran.tsv")
DEFAULT_PICKTHALL = os.path.join(HOME, "Documents/workspace_islam/sources/pickthall.tsv")
DEFAULT_OUT = os.path.join(HOME, "Documents/workspace_islam/ChineseReaderText_staging/islam")
CHUNK = 10
# Verses per surah in the standard (Hafs, Kufan) numbering: 6,236 in all.
AYAHS = [7, 286, 200, 176, 120, 165, 206, 75, 129, 109, 123, 111, 43, 52, 99, 128, 111, 110, 98, 135,
         112, 78, 118, 64, 77, 227, 93, 88, 69, 60, 34, 30, 73, 54, 45, 83, 182, 88, 75, 85, 54, 53, 89,
         59, 37, 35, 38, 29, 18, 45, 60, 49, 62, 55, 78, 96, 29, 22, 24, 13, 14, 11, 11, 18, 12, 12, 30,
         52, 52, 44, 28, 28, 20, 56, 40, 31, 50, 40, 46, 42, 29, 19, 36, 25, 22, 17, 19, 26, 30, 20, 15,
         21, 11, 8, 8, 19, 5, 8, 8, 11, 11, 8, 3, 9, 5, 4, 7, 3, 6, 3, 5, 4, 5, 6]   # verses per ## section (the Bible pages use small sections too)


def cell(text):
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def surah_name(slug):
    """al-fatihah → Al-Fatihah; ali-imran → Ali-Imran."""
    return "-".join(p[:1].upper() + p[1:] for p in slug.split("-"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tsv", default=DEFAULT_TSV)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--pickthall", default=DEFAULT_PICKTHALL,
                    help="surah<TAB>ayah<TAB>text: Pickthall's English (1930, public domain); '' to leave it out")
    ap.add_argument("--no-english", action="store_true", help="leave out the Sahih International column")
    args = ap.parse_args()

    surahs = OrderedDict()
    with open(args.tsv, encoding="utf-8") as f:
        for r in csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE):
            n = int(r["surah"])
            slug = re.search(r"quran\.com/([^/]+)/", r.get("verse_url") or "")
            s = surahs.setdefault(n, {"slug": slug.group(1) if slug else f"surah-{n}", "verses": []})
            s["verses"].append((int(r["ayah"]), r["arabic"], r["english"]))

    pickthall = {}
    if args.pickthall and os.path.exists(args.pickthall):
        with open(args.pickthall, encoding="utf-8") as f:
            for r in csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE):
                pickthall[(int(r["surah"]), int(r["ayah"]))] = r["text"]
    english = not args.no_english
    os.makedirs(os.path.join(args.out, "quran"), exist_ok=True)
    labels = ["Arabic", "Romanization"] + (["Pickthall"] if pickthall else []) + (["Sahih International"] if english else [])
    header = "| " + " | ".join(labels) + " |"
    rule = "|" + "---|" * len(labels)

    index = []
    total = 0
    for n, s in surahs.items():
        name = surah_name(s["slug"])
        fname = f"{n:03d}-{s['slug']}.md"
        verses = sorted(s["verses"])
        total += len(verses)
        lines = [
            "<!-- reader: lang=ar -->",
            "",
            f"# {n}. {name}",
            "",
            "> Arabic (Uthmani script) · Romanization (generated, approximate)"
            + (" · Pickthall, The Meaning of the Glorious Koran (1930)" if pickthall else "")
            + (" · Sahih International English (© Saheeh International)" if english else ""),
            "",
        ]
        for i in range(0, len(verses), CHUNK):
            part = verses[i:i + CHUNK]
            a, b = part[0][0], part[-1][0]
            lines += [f"## Verses {a}–{b}" if a != b else f"## Verse {a}", "", "<!-- reader: table=verses -->", header, rule]
            for ayah, arabic, eng in part:
                cols = [cell(arabic), cell(arabic_roman.verse(arabic))]
                if pickthall:
                    cols.append(cell(pickthall.get((n, ayah), "")))
                if english:
                    cols.append(cell(eng))
                cols[0] = f"{ayah} {cols[0]}"   # the verse number leads the first cell
                lines.append("| " + " | ".join(cols) + " |")
            lines.append("")
        with open(os.path.join(args.out, "quran", fname), "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
        index.append((n, f"- [{n}. {name} ({len(verses)})](quran/{fname})"))

    readme = ["## Islamic Texts", ""]
    for start in range(1, 115, 20):
        end = min(start + 19, 114)
        readme += [f"### The Qur'an · Surahs {start}–{end}", ""] + [line for n, line in index if start <= n <= end] + [""]
    with open(os.path.join(args.out, "README.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(readme))
    with open(os.path.join(args.out, "catalog-entry.md"), "w", encoding="utf-8") as f:
        f.write("## islam · Islamic Texts\n- index: [islam/README.md](islam/README.md)\n"
                "- The Qur'an: the 114 surahs in Arabic (Uthmani script) with a romanization"
                + (", Pickthall's English" if pickthall else "")
                + (" and the Sahih International English" if english else "") + ".\n")
    print(f"{len(surahs)} surahs, {total} verses → {args.out}")
    missing = [f"{n}:{a}" for n, count in enumerate(AYAHS, 1)
               for a in sorted(set(range(1, count + 1)) - {v[0] for v in surahs.get(n, {"verses": []})["verses"]})]
    if missing:
        print(f"Missing from {os.path.basename(args.tsv)} ({len(missing)}): {', '.join(missing)}")


if __name__ == "__main__":
    main()
